#!/usr/bin/env python3
"""Lockfile gates: every committed Cargo.lock is current, and every one is audited.

WHY IT EXISTS. `fuzz/` is its own cargo workspace, and until this change its
`Cargo.lock` was gitignored. Its dependencies were re-resolved on every CI run,
so a dependency release could break the fuzz job with no commit in this repo
(that is what broke spar's required fuzz job). The advisory audit ran in the
root workspace only, so a lock outside it was never audited.

TWO MODES, each a real check followed by a planted control:

  freshness  `cargo metadata --locked` in the directory of every committed
             Cargo.lock. It fails when a lock is out of date with its
             manifests. It also refuses a cargo workspace root that has no
             committed lock, which is the shape of the fuzz/ gap.
  audit      `cargo deny check advisories` for every committed Cargo.lock,
             with the repository's own deny.toml.

THE POPULATION IS DISCOVERED with `git ls-files`, never listed here, and an
empty discovery is an error: a check over no lockfiles would pass about nothing.

THE PLANTED CONTROLS run on every invocation and the script fails if either
one passes:

  freshness  a temp crate gets a dependency added to Cargo.toml with its lock
             left alone; `cargo metadata --locked` must fail there, having
             passed before the edit.
  audit      a temp workspace's lock pins smallvec 1.6.0 (RUSTSEC-2021-0003,
             buffer overflow in `insert_many`, fixed in 1.6.1); `cargo deny
             check advisories` must fail there and must name that advisory.

NOT COVERED: MODULE.bazel.lock. See the note in .bazelrc.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PLANTED_ADVISORY = "RUSTSEC-2021-0003"
PLANTED_ADVISORY_MANIFEST = """\
[package]
name = "planted-advisory"
version = "0.0.0"
edition = "2021"
publish = false

[workspace]

[dependencies]
smallvec = "=1.6.0"
"""
# Written out, not generated, so the control does not depend on the resolver
# still being willing to select this version.
PLANTED_ADVISORY_LOCK = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "planted-advisory"
version = "0.0.0"
dependencies = [
 "smallvec",
]

[[package]]
name = "smallvec"
version = "1.6.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "1a55ca5f3b68e41c979bf8c46a6f1da892ca4db8f94023ce0bd32407573b1ac0"
"""

PLANTED_STALE_MANIFEST = """\
[package]
name = "planted-stale"
version = "0.0.0"
edition = "2021"
publish = false

[workspace]

[dependencies]
"""
PLANTED_EXTRA_MANIFEST = """\
[package]
name = "planted-extra"
version = "0.0.0"
edition = "2021"
publish = false
"""


def run(cmd, cwd):
    """Run cmd, return (rc, combined output). Never raises on a non-zero rc."""
    p = subprocess.run(
        cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
    )
    return p.returncode, p.stdout


def git_ls(*patterns):
    p = subprocess.run(
        ["git", "ls-files", "-z", "--", *patterns],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        text=True,
    )
    if p.returncode != 0:
        sys.exit(f"FAIL: git ls-files exited {p.returncode}; cannot discover lockfiles")
    return sorted(Path(x) for x in p.stdout.split("\0") if x)


def discover_locks():
    locks = git_ls("Cargo.lock", "**/Cargo.lock")
    if not locks:
        sys.exit("FAIL: no committed Cargo.lock found; refusing to pass about nothing")
    for lock in locks:
        if not (ROOT / lock.parent / "Cargo.toml").is_file():
            sys.exit(f"FAIL: {lock} has no Cargo.toml beside it")
    return locks


def workspace_roots_without_lock(locks):
    """Committed Cargo.toml files that are workspace roots with no committed lock."""
    locked_dirs = {lock.parent for lock in locks}
    missing = []
    for manifest in git_ls("Cargo.toml", "**/Cargo.toml"):
        text = (ROOT / manifest).read_text(encoding="utf-8")
        if re.search(r"^\[workspace[\].]", text, re.MULTILINE):
            if manifest.parent not in locked_dirs:
                missing.append(manifest)
    return missing


def freshness_control(tmp):
    """True when `cargo metadata --locked` refuses a lock its manifest outran."""
    crate = Path(tmp) / "planted-stale"
    (crate / "src").mkdir(parents=True)
    (crate / "extra" / "src").mkdir(parents=True)
    (crate / "src" / "lib.rs").write_text("")
    (crate / "extra" / "src" / "lib.rs").write_text("")
    (crate / "extra" / "Cargo.toml").write_text(PLANTED_EXTRA_MANIFEST)
    manifest = crate / "Cargo.toml"
    manifest.write_text(PLANTED_STALE_MANIFEST)

    rc, out = run(["cargo", "generate-lockfile", "--offline"], crate)
    if rc != 0:
        print(f"FAIL(control scaffold): could not create the planted lock\n{out}")
        return False
    locked = ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"]
    rc, out = run(locked, crate)
    if rc != 0:
        print(f"FAIL(control scaffold): the planted crate's fresh lock was refused\n{out}")
        return False

    before = (crate / "Cargo.lock").read_bytes()
    manifest.write_text(PLANTED_STALE_MANIFEST + 'planted-extra = { path = "extra" }\n')
    rc, out = run(locked, crate)
    if rc == 0:
        print("FAIL(control): `cargo metadata --locked` PASSED on a lock that is")
        print("out of date with its manifest, so the freshness check cannot fail.")
        return False
    if "lock" not in out.lower():
        print(f"FAIL(control): it failed, but not about the lock file:\n{out}")
        return False
    if (crate / "Cargo.lock").read_bytes() != before:
        print("FAIL(control): --locked rewrote the lock it was meant to protect")
        return False
    print(f"control OK: the stale planted lock is refused (rc {rc})")
    return True


def cmd_freshness():
    ok = True
    locks = discover_locks()
    print(f"committed Cargo.lock files: {len(locks)}")
    for lock in locks:
        rc, out = run(
            ["cargo", "metadata", "--locked", "--format-version", "1"],
            ROOT / lock.parent,
        )
        if rc == 0:
            print(f"  fresh   {lock}")
        else:
            ok = False
            tail = "\n".join(l for l in out.splitlines() if not l.startswith("{"))
            print(f"  STALE   {lock} (rc {rc})\n{tail}")
            print(f"::error file={lock}::{lock} is out of date with its manifests. "
                  f"Run `cargo metadata` in {lock.parent or '.'} and commit the result.")
    for manifest in workspace_roots_without_lock(locks):
        ok = False
        print(f"  NO LOCK {manifest} is a workspace root with no committed Cargo.lock")
        print(f"::error file={manifest}::{manifest} is a cargo workspace root with no "
              "committed Cargo.lock, so its dependencies are re-resolved on every build.")
    with tempfile.TemporaryDirectory() as tmp:
        ok = freshness_control(tmp) and ok
    return ok


def deny(manifest_dir):
    return run(
        [
            "cargo", "deny", "--locked",
            "--manifest-path", str(Path(manifest_dir) / "Cargo.toml"),
            "--config", str(ROOT / "deny.toml"),
            "check", "advisories",
        ],
        manifest_dir,
    )


def audit_control(tmp):
    """True when cargo-deny, with this repo's deny.toml, refuses a known advisory."""
    crate = Path(tmp) / "planted-advisory"
    (crate / "src").mkdir(parents=True)
    (crate / "src" / "lib.rs").write_text("")
    (crate / "Cargo.toml").write_text(PLANTED_ADVISORY_MANIFEST)
    (crate / "Cargo.lock").write_text(PLANTED_ADVISORY_LOCK)
    rc, out = deny(crate)
    if rc == 0:
        print(f"FAIL(control): the audit PASSED a lock pinning smallvec 1.6.0")
        print(f"({PLANTED_ADVISORY}), so it cannot report an advisory.")
        return False
    if "error[vulnerability]" not in out or PLANTED_ADVISORY not in out:
        print(f"FAIL(control): the audit failed, but not on {PLANTED_ADVISORY}:\n{out}")
        return False
    print(f"control OK: the planted {PLANTED_ADVISORY} lock is refused (rc {rc})")
    return True


def cmd_audit():
    ok = True
    locks = discover_locks()
    print(f"committed Cargo.lock files: {len(locks)}")
    for lock in locks:
        rc, out = deny(ROOT / lock.parent)
        if rc == 0:
            print(f"  clean   {lock}")
        else:
            ok = False
            print(f"  ADVISORY {lock} (rc {rc})\n{out}")
            print(f"::error file={lock}::cargo deny check advisories failed for {lock}")
    with tempfile.TemporaryDirectory() as tmp:
        ok = audit_control(tmp) and ok
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mode", choices=["freshness", "audit"])
    args = ap.parse_args()
    os.environ.setdefault("CARGO_TERM_COLOR", "never")
    ok = cmd_freshness() if args.mode == "freshness" else cmd_audit()
    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
