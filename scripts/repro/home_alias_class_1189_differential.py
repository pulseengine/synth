def run_rv32(obj, name, sig, args):
    syms, text, base = obj
    if name not in syms:
        return None, f"symbol {name} missing from .symtab"
    widths, ret = sig
    addr = syms[name] - base
    mu = Uc(UC_ARCH_RISCV, UC_MODE_RISCV32)
    mu.mem_map(CODE, 0x40000)
    mu.mem_map(LIN, 0x20000)
    mu.mem_map(STACK_BASE, STACK_SIZE)
    mu.mem_map(RET_FLAT, 0x1000)
    mu.mem_write(CODE, text)
    mu.mem_write(LIN, PREFILL)
    mu.mem_write(STACK_BASE,
                 struct.pack("<I", MEM_POISON) * ((SP0 - STACK_BASE) // 4))
    for reg, i in RV_SEED:
        mu.reg_write(reg, canary(i))
    mu.reg_write(rc.UC_RISCV_REG_SP, SP0)
    mu.reg_write(rc.UC_RISCV_REG_S11, LIN)
    regs = [rc.UC_RISCV_REG_A0, rc.UC_RISCV_REG_A1, rc.UC_RISCV_REG_A2,
            rc.UC_RISCV_REG_A3]
    _pack_args32(mu.reg_write, regs, widths, args)
    mu.reg_write(rc.UC_RISCV_REG_RA, RET_FLAT)
    try:
        mu.emu_start(CODE + addr, RET_FLAT, count=400_000)
    except UcError as ex:
        return None, str(ex)
    a0 = mu.reg_read(rc.UC_RISCV_REG_A0) & M32
    if ret == 64:
        return a0 | (mu.reg_read(rc.UC_RISCV_REG_A1) & M32) << 32, ""
    return a0, ""


def run_a64(obj, name, sig, args):
    syms, text, base = obj
    if name not in syms:
        return None, f"symbol {name} missing from .symtab"
    widths, ret = sig
    addr = (syms[name] - base) & ~1
    mu = Uc(UC_ARCH_ARM64, UC_MODE_ARM)
    mu.mem_map(CODE, 0x40000)
    mu.mem_map(STACK_BASE, STACK_SIZE)
    mu.mem_map(RET_FLAT, 0x1000)
    mu.mem_map(LIN_A64, 0x20000)
    mu.mem_write(CODE, text)
    mu.mem_write(LIN_A64, PREFILL)
    mu.reg_write(a64.UC_ARM64_REG_SP, SP0)
    mu.reg_write(a64.UC_ARM64_REG_LR, RET_FLAT)
    for i in range(0, 16):
        mu.reg_write(getattr(a64, f"UC_ARM64_REG_X{i}"), canary(i))
    mu.reg_write(a64.UC_ARM64_REG_X28, LIN_A64)
    regs = [a64.UC_ARM64_REG_X0, a64.UC_ARM64_REG_X1, a64.UC_ARM64_REG_X2,
            a64.UC_ARM64_REG_X3]
    for r, (w, a) in zip(regs, zip(widths, args)):
        mu.reg_write(r, a & (M32 if w == 32 else M64))
    try:
        mu.emu_start(CODE + addr, RET_FLAT, count=400_000)
    except UcError as ex:
        return None, str(ex)
    if ret == 32:
        return mu.reg_read(a64.UC_ARM64_REG_W0) & M32, ""
    return mu.reg_read(a64.UC_ARM64_REG_X0) & M64, ""


def run_leg(leg, obj, name, sig, args):
    if leg.startswith("arm"):
        return run_arm(obj, name, sig, args, leg == "arm-self")
    if leg.startswith("rv32"):
        return run_rv32(obj, name, sig, args)
    return run_a64(obj, name, sig, args)


# ── the reference ───────────────────────────────────────────────────────────
class Reference:
    """wasmtime, one fresh instance per call (bulk ops mutate memory), memory
    pre-filled with PREFILL exactly like the emulators."""

    def __init__(self):
        self.engine = wasmtime.Engine()
        self.modules = {}

    def module(self, name):
        if name not in self.modules:
            self.modules[name] = wasmtime.Module.from_file(self.engine,
                                                            str(MODULES[name]))
        return self.modules[name]

    def signatures(self, name):
        """fn -> ([param widths], ret width) from the export types."""
        out = {}
        for exp in self.module(name).exports:
            if isinstance(exp.type, wasmtime.FuncType):
                widths = [64 if str(p) == "i64" else 32 for p in exp.type.params]
                rets = exp.type.results
                if len(rets) != 1:
                    die(f"{name}/{exp.name}: expected exactly one result")
                out[exp.name] = (widths, 64 if str(rets[0]) == "i64" else 32)
        return out

    def call(self, name, fn, sig, args):
        widths, ret = sig
        store = wasmtime.Store(self.engine)
        inst = wasmtime.Instance(store, self.module(name), [])
        exports = inst.exports(store)
        if "memory" in exports:
            exports["memory"].write(store, PREFILL, 0)
        f = exports[fn]
        call = []
        for w, a in zip(widths, args):
            if w == 32:
                call.append(struct.unpack("<i", struct.pack("<I", a & M32))[0])
            else:
                call.append(struct.unpack("<q", struct.pack("<Q", a & M64))[0])
        return f(store, *call) & (M32 if ret == 32 else M64)


def compile_module(module, leg, out):
    return subprocess.run(
        [SYNTH, "compile", str(MODULES[module]), *LEG_FLAGS[leg],
         "--all-exports", "--allow-skipped-exports", "-o", out],
        capture_output=True, text=True, env={"PATH": "/usr/bin:/bin"},
    )


def fmt(v):
    return f"{v:#x}" if v is not None else "<none>"


def capture(old_synth, rev):
    fix = {
        "provenance": {
            "issue": "#1189 / RQ-65-ALIASCLASS",
            "source_rev": rev,
            "note": "objects emitted by main's compiler for the legs carrying "
                    "the #1221/#1222/#1223 wrong vectors; recipe in this "
                    "oracle's docstring",
        },
        "legs": {},
    }
    saved = globals()["SYNTH"]
    globals()["SYNTH"] = old_synth
    try:
        for module, leg in FIXTURE_LEGS:
            with tempfile.TemporaryDirectory() as td:
                out = os.path.join(td, "m.o")
                r = compile_module(module, leg, out)
                if not os.path.exists(out):
                    die(f"capture: {module}/{leg} produced no object:\n{r.stderr[-600:]}")
                blob = Path(out).read_bytes()
            fix["legs"][f"{module}_{leg}"] = {"object_b64": base64.b64encode(blob).decode()}
            print(f"captured {module}/{leg}: {len(blob)} bytes")
    finally:
        globals()["SYNTH"] = saved
    FIXTURE.write_text(json.dumps(fix, indent=2) + "\n")
    print(f"wrote {FIXTURE}")
    return 0


def main():
    argv = sys.argv[1:]
    if len(argv) == 4 and argv[0] == "--capture" and argv[2] == "--rev":
        return capture(argv[1], argv[3])
    print_skips = argv == ["--print-skips"]
    if argv and not print_skips:
        die(f"usage: {sys.argv[0]} [--print-skips | --capture <main synth> --rev <sha>]")

    ref = Reference()
    fails = 0
    emulations = 0

    # ── RED half: main's own bytes vs wasmtime ──────────────────────────────
    fix = json.loads(FIXTURE.read_text())
    print(f"== red half: fixture rev {fix['provenance']['source_rev'][:12]} (main) ==")
    wrong_seen = fix_match = 0
    pinned_hit = set()
    for module, leg in FIXTURE_LEGS:
        entry = fix["legs"].get(f"{module}_{leg}")
        if entry is None:
            die(f"fixture leg {module}/{leg} missing; re-capture")
        obj = load_object(base64.b64decode(entry["object_b64"]), leg)
        sigs = ref.signatures(module)
        for fn, sig in sigs.items():
            if fn not in obj[0]:
                continue  # main declined it; the live half pins declines
            for args in vectors(module, fn):
                want = ref.call(module, fn, sig, args)
                got, err = run_leg(leg, obj, fn, sig, args)
                emulations += 1
                if err:
                    print(f"  FAIL fixture {module}/{leg} {fn}{tuple(args)}: emulator error: {err}")
                    fails += 1
                    continue
                key = (module, leg, fn, tuple(args))
                pinned = PINNED_WRONG.get(key)
                if pinned is not None:
                    ok = got == pinned and got != want
                    wrong_seen += ok
                    pinned_hit.add(key)
                    label = ("SILENT-WRONG as pinned" if ok
                             else f"NOT the pinned miscompile (pinned {pinned:#x})")
                    print(f"  {'ok  ' if ok else 'FAIL'} fixture {module}/{leg} "
                          f"{fn}{tuple(args)} -> {fmt(got)} (wasmtime {want:#x}) — {label}")
                else:
                    ok = got == want
                    fix_match += ok
                    if not ok:
                        print(f"  FAIL fixture {module}/{leg} {fn}{tuple(args)} -> "
                              f"{fmt(got)} (wasmtime {want:#x}) — diverged, not pinned")
                fails += not ok
    missing = set(PINNED_WRONG) - pinned_hit
    if missing:
        print(f"  FAIL pinned wrong vectors never executed: {sorted(missing)}")
        fails += 1

    # ── LIVE half: the current compiler on all four legs ────────────────────
    print("== live half: current compiler vs wasmtime, four legs ==")
    live_ok = live_bad = open_seen = 0
    measured_skips = {}
    for module in MODULES:
        sigs = ref.signatures(module)
        for leg in LEGS:
            with tempfile.TemporaryDirectory() as td:
                out = os.path.join(td, "m.o")
                r = compile_module(module, leg, out)
                log = r.stderr + r.stdout
                if "panicked at" in log or r.returncode == 101:
                    print(f"  FAIL {module}/{leg}: PANIC:\n{log[-600:]}")
                    fails += 1
                    continue
                if not os.path.exists(out):
                    print(f"  FAIL {module}/{leg}: no object (rc={r.returncode}):"
                          f"\n{log[-600:]}")
                    fails += 1
                    continue
                obj = load_object(Path(out).read_bytes(), leg)
            syms = obj[0]
            missing = {fn for fn in sigs if fn not in syms}
            measured_skips[(module, leg)] = missing
            expected = EXPECTED_SKIPS.get((module, leg), set())
            if missing != expected and not print_skips:
                new = sorted(missing - expected)
                gone = sorted(expected - missing)
                print(f"  FAIL {module}/{leg}: decline table drifted — "
                      f"newly declined {new}, now compiling {gone}")
                fails += 1
            for fn, sig in sigs.items():
                if fn in missing:
                    continue
                for args in vectors(module, fn):
                    want = ref.call(module, fn, sig, args)
                    got, err = run_leg(leg, obj, fn, sig, args)
                    emulations += 1
                    if err:
                        print(f"  FAIL {module}/{leg} {fn}{tuple(args)}: "
                              f"emulator error: {err}")
                        live_bad += 1
                        continue
                    known = KNOWN_OPEN.get((module, leg, fn, tuple(args)))
                    if known is not None:
                        rec, issue = known
                        ok = got == rec and got != want
                        open_seen += ok
                        note = (f"still the recorded wrong answer, {issue} open" if ok
                                else f"pin drifted: fix landed or value moved ({issue})")
                        print(f"  {'ok  ' if ok else 'FAIL'} {module}/{leg} {fn}{tuple(args)} -> "
                              f"{fmt(got)} (wasmtime {want:#x}) — {note}")
                        live_ok += ok
                        live_bad += not ok
                        continue
                    ok = got == want
                    live_ok += ok
                    live_bad += not ok
                    if not ok:
                        print(f"  FAIL {module}/{leg} {fn}{tuple(args)} -> "
                              f"{fmt(got)} (wasmtime: {want:#x}) — SILENT WRONG ANSWER")
            print(f"  {module}/{leg}: {len(sigs) - len(missing)} functions executed, "
                  f"{len(missing)} declined")
    fails += live_bad

    if print_skips:
        print("EXPECTED_SKIPS = {")
        for (m, leg), sk in sorted(measured_skips.items()):
            if sk:
                print(f'    ("{m}", "{leg}"): {sorted(sk)!r},')
        print("}")
        return 0

    print(f"\nsilent-wrong vectors: {wrong_seen} (of {len(PINNED_WRONG)} pinned); "
          f"fixture match vectors: {fix_match}")
    print(f"known-open vectors: {open_seen} (of {len(KNOWN_OPEN)})")
    print(f"live vectors: {live_ok} matched, {live_bad} diverged")
    print(f"emulations: {emulations}")
    if wrong_seen != len(PINNED_WRONG):
        print(f"VACUOUS: silent-wrong vectors={wrong_seen}, want {len(PINNED_WRONG)} — "
              f"the red half no longer demonstrates the miscompiles it exists to remember")
        return 1
    if fix_match == 0 or live_ok == 0:
        print("VACUOUS: no match vector executed")
        return 1
    if fails:
        print(f"RESULT: FAIL ({fails})")
        return 1
    print("RESULT: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
