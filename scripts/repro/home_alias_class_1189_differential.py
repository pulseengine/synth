"""RQ-65-ALIASCLASS (#1189) — the home-register alias class, executed per
consumer family on all four legs.

THE MECHANISM. `local.get` of a register-homed local pushes THE HOME
REGISTER uncopied. #677 (bulk-memory pointer walk), #989 (get→set→use) and
#1189 (if/else join) were three consumers that wrote it, each a silent wrong
answer. The static half of this artifact (`synth_synthesis::home_alias`, run
over the corpus by `home_alias_audit_corpus_1189.py`) proves no emitted
instruction of the ARM direct selector writes a live home. THIS half asks
the same question by EXECUTION, per consumer family, on every leg — because
the static audit covers exactly one selector (the ARM direct one) and the
other three legs alias too:

  arm-reloc   direct selector `select_with_stack` (#197): params r0–r3 and
              promoted locals r4–r8 pushed uncopied — the audited leg.
  arm-self    the OPTIMIZED selector for these straight-line shapes:
              `ir_to_arm` maps a `local.get`'s vreg straight onto the param
              register (no copy either); shapes it declines fall to the
              direct selector.
  rv32-reloc  params are COPIED on `local.get` (`mv dst, a_n`) — a promoted
              local (`s8..s10`, #472) is aliased uncopied.
  aarch64     a leaf function that never writes a param pushes the AAPCS64
              register itself (`stack.push(params[i])`).

Every function feeds params homed in r0..r3 (or, in `promo`, a local the
selectors promote) to ONE consumer op and then RE-READS every home into the
result — a consumer that wrote a home in place returns a wrong number, not a
lucky one. Families: i32/i64 binary, compare, unary; conversions; loads and
stores (home as address and as value); select (home as arm and as
condition); function-level `br_if` with a home value; `br_table` on a home
index; `if (param)` whose param is a home (RQ-64-MVLOWER); block fall-
through; a param-bounded loop (#663); set/tee of ANOTHER local; the #989 WAR;
`memory.fill`/`memory.copy` on home operands (#677). The modules are
generated by `scripts/gen_home_alias_class_1189.py` and committed.

EVERY expected value comes from wasmtime, live; linear memory is pre-filled
with the same byte pattern on both sides so loads are meaningful and stores
are observed. Signatures are read from the module's export types — nothing
is typed twice.

DECLINES ARE PINNED EXACTLY. A leg that refuses a function (RV32's #312 i64
params; AArch64 shapes it does not lower yet) leaves no symbol; the set of
missing symbols per (module, leg) must EQUAL the table below — an
unexpected decline is red (reach regressed), and a pinned decline that now
compiles is red too (reach moved; update the pin in the PR that moved it).

TWO HALVES, ONE CASE TABLE (the #1190 discipline). The oracle's first run
on main (`af819788`) found THREE silent wrong answers, each a different
consumer: #1221 (aarch64 `rotl` negates the count operand IN PLACE — a param
homed there reads back as `-count`), #1222 (the direct selector's
`local.set`/`local.tee` of a register-homed i64 param writes only the LO
half), #1223 (the optimized path folds `(x - x) + x` to the constant 0 — an
IR fold/DCE defect, not an alias, filed and pinned OPEN).
  RED half  — `home_alias_class_1189_red_main.json` holds the objects main
              emitted for the five (module, leg) pairs carrying those
              vectors. Every run re-executes them; the pinned vectors must
              return EXACTLY the recorded wrong value AND differ from live
              wasmtime, the rest must match. The permanent proof this
              harness can see the defects — a differential that has never
              been red is a green board of unknown potency.
  LIVE half — the current compiler on all four legs must match wasmtime,
              except the KNOWN_OPEN vectors (#1223), which must still return
              the recorded wrong value until their fix flips the pin.

CAPTURE (how the fixture was made, and how to remake it): check out main at
af819788 in a scratch tree, `cargo build --features riscv --bin synth`, then
  python3 scripts/repro/home_alias_class_1189_differential.py \
      --capture <that tree>/target/debug/synth --rev af819788

Run (needs wasmtime + unicorn + pyelftools):
  SYNTH=./target/debug/synth python3 scripts/repro/home_alias_class_1189_differential.py
  … --print-skips   prints the measured decline table (to re-derive the pin)
"""

