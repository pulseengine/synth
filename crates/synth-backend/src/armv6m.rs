//! RQ-91-ARMV6M (#1301): the ARMv6-M instruction check.
//!
//! ARMv6-M (Cortex-M0/M0+) executes the 16-bit Thumb subset plus a handful of
//! 32-bit instructions. synth's selector and encoder are ARMv7-M ones, so the
//! cortex-m0 / cortex-m0plus profiles do NOT lower anything differently: every
//! instruction the encoder emits for one of those profiles is checked HERE, on
//! its ENCODED BYTES, and a function containing anything outside ARMv6-M is
//! refused, loudly, naming the offset and the class. Whatever compiles on the
//! profile is ARMv6-M by this check; everything else declines. This is support
//! LEVEL 3: no correctness claim beyond what this check and execution show.
//!
//! WHY BYTES AND NOT `ArmOp` VARIANTS. The encoder expands one `ArmOp` into an
//! instruction SEQUENCE in many arms (IT blocks for selects, MOVW/MOVT pairs,
//! wide forms chosen by register or immediate range). A list of refused
//! variants would be a hand-maintained mirror of 224 encoder arms; checking
//! the bytes the encoder actually produced is the shipped artifact itself.
//!
//! THE 16-BIT TABLE IS DERIVED, NOT WRITTEN. [`LEGAL_16`] is every 16-bit
//! halfword that LLVM's `thumbv6m-none-eabi` decoder accepts, enumerated over
//! all 59,392 non-prefix halfwords by `scripts/repro/armv6m_legality_1301.py
//! --regen` and frozen in `tests/fixtures/armv6m_legal16_1301.json`; the
//! unit test below re-checks this table against that fixture exhaustively.
//! Against the `thumbv7m` decode the excluded set is exactly CBZ/CBNZ
//! (0xB100-0xB1FF, 0xB300-0xB3FF, 0xB900-0xB9FF, 0xBB00-0xBBFF) and IT
//! (0xBFx1-0xBFxF); the rest of the excluded set is undefined in both.
//!
//! 32-BIT: deliberately STRICTER than ARMv6-M. ARMv6-M has BL, MSR, MRS,
//! DMB/DSB/ISB and UDF.W as 32-bit instructions. synth emits none but BL, so
//! only BL and the three full-system barriers pass; MSR/MRS/UDF.W are refused
//! (a stricter check can only refuse more, never accept an illegal word).
//!
//! LITERAL POOLS. synth's literal-pool load (`LdrSym`) is the 32-bit LDR.W
//! (literal), 4 KB reach; ARMv6-M's LDR (literal) is 16-bit with a 1020-byte
//! forward reach. LDR.W is not ARMv6-M, so this check refuses every function
//! with a pool load and the 4 KB island planner is never consulted for an
//! ARMv6-M function. The 16-bit LDR (literal), 0x4800-0x4FFF, IS ARMv6-M (it is
//! in [`LEGAL_16`]) but is refused HERE too, by a separate rule: synth places
//! no pool against the 1020-byte reach, so nothing has checked that the word a
//! 16-bit literal load reads is the one it means. Adding a 16-bit pool load for
//! this profile means lifting this rule together with a reach check.

