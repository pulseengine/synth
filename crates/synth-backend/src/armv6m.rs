/// Why an instruction is not ARMv6-M. The class names the ARMv6-M restriction
/// it hits, so the diagnostic says what kind of lowering is missing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum V6mViolation {
    /// `IT` (If-Then): ARMv6-M has no conditional execution of non-branches.
    It(u16),
    /// `CBZ` / `CBNZ`.
    CbzCbnz(u16),
    /// A 16-bit encoding the ARMv6-M decoder does not accept.
    Undefined16(u16),
    /// A 16-bit LDR (literal): ARMv6-M, but refused because no pool reach
    /// (1020 bytes on ARMv6-M, against the 4 KB the island planner assumes)
    /// has been checked for it.
    LdrLiteral16(u16),
    /// A 32-bit Thumb-2 instruction other than BL / DMB / DSB / ISB.
    Wide {
        /// First halfword.
        hw1: u16,
        /// Second halfword.
        hw2: u16,
        /// The class of the 32-bit instruction.
        class: &'static str,
    },
    /// A 32-bit prefix halfword with no second halfword in the encoding.
    Truncated(u16),
}

impl V6mViolation {
    /// The restriction class, for diagnostics and census.
    pub fn class(&self) -> &'static str {
        match self {
            Self::It(_) => "IT block",
            Self::CbzCbnz(_) => "CBZ/CBNZ",
            Self::Undefined16(_) => "16-bit encoding not in ARMv6-M",
            Self::LdrLiteral16(_) => "16-bit LDR literal: pool reach not checked on ARMv6-M",
            Self::Wide { class, .. } => class,
            Self::Truncated(_) => "truncated 32-bit encoding",
        }
    }

    /// The instruction bytes, as halfwords in hex.
    pub fn bytes_hex(&self) -> String {
        match self {
            Self::It(h)
            | Self::CbzCbnz(h)
            | Self::Undefined16(h)
            | Self::LdrLiteral16(h)
            | Self::Truncated(h) => {
                format!("{h:04x}")
            }
            Self::Wide { hw1, hw2, .. } => format!("{hw1:04x} {hw2:04x}"),
        }
    }
}

/// Whether `hw` begins a 32-bit Thumb encoding.
pub fn is_wide_prefix(hw: u16) -> bool {
    matches!(hw >> 11, 0b11101..=0b11111)
}

/// Whether the 16-bit halfword `hw` is an ARMv6-M instruction.
pub fn legal_16(hw: u16) -> bool {
    LEGAL_16.iter().any(|&(lo, hi)| (lo..=hi).contains(&hw))
}

/// Whether `hw` is the 16-bit LDR (literal), `0100 1 Rt imm8`.
pub fn is_ldr_literal_16(hw: u16) -> bool {
    hw & 0xF800 == 0x4800
}

/// Whether the 32-bit encoding `hw1 hw2` passes (BL, DMB SY, DSB SY, ISB SY).
pub fn legal_32(hw1: u16, hw2: u16) -> bool {
    let bl = hw1 >> 11 == 0b11110 && hw2 & 0xD000 == 0xD000;
    let barrier = hw1 == 0xF3BF && matches!(hw2, 0x8F4F | 0x8F5F | 0x8F6F);
    bl || barrier
}

/// Coarse class of a refused 32-bit encoding (diagnostic only — the verdict
/// is [`legal_32`], never this).
fn wide_class(hw1: u16, hw2: u16) -> &'static str {
    match hw1 {
        // MOVW T3 / MOVT T1: 11110 i 10 0 1 0 0 imm4 / 11110 i 10 1 1 0 0 imm4
        _ if hw1 & 0xFBF0 == 0xF240 || hw1 & 0xFBF0 == 0xF2C0 => "MOVW/MOVT",
        _ if hw1 & 0xFFF0 == 0xFB90 || hw1 & 0xFFF0 == 0xFBB0 => "UDIV/SDIV",
        _ if hw1 & 0xFF80 == 0xFB00 || hw1 & 0xFF80 == 0xFB80 => "wide multiply",
        _ if hw1 >> 9 == 0b1111100 => "wide load/store",
        _ if hw1 & 0xFE40 == 0xE840 => "LDRD/STRD/exclusive/table branch",
        _ if hw1 & 0xFE40 == 0xE800 => "wide load/store multiple (PUSH/POP/LDM/STM)",
        _ if hw1 >> 11 == 0b11110 && hw2 & 0x8000 == 0x8000 => {
            "wide branch or system (B.W/Bcc.W/MRS/MSR)"
        }
        _ if hw1 & 0xEC00 == 0xEC00 => "coprocessor/FPU",
        _ => "wide data-processing",
    }
}

/// Check every instruction in `bytes` (one encoded instruction or sequence,
/// containing no data). Returns the byte offset within `bytes` and the
/// violation of the FIRST non-ARMv6-M instruction.
pub fn check_bytes(bytes: &[u8]) -> Result<(), (usize, V6mViolation)> {
    let mut off = 0;
    while off + 1 < bytes.len() {
        let hw = u16::from_le_bytes([bytes[off], bytes[off + 1]]);
        if is_wide_prefix(hw) {
            if off + 3 >= bytes.len() {
                return Err((off, V6mViolation::Truncated(hw)));
            }
            let hw2 = u16::from_le_bytes([bytes[off + 2], bytes[off + 3]]);
            if !legal_32(hw, hw2) {
                let class = wide_class(hw, hw2);
                return Err((
                    off,
                    V6mViolation::Wide {
                        hw1: hw,
                        hw2,
                        class,
                    },
                ));
            }
            off += 4;
        } else {
            if is_ldr_literal_16(hw) {
                return Err((off, V6mViolation::LdrLiteral16(hw)));
            }
            if !legal_16(hw) {
                let v = if hw & 0xFF00 == 0xBF00 {
                    V6mViolation::It(hw)
                } else if hw & 0xF500 == 0xB100 {
                    V6mViolation::CbzCbnz(hw)
                } else {
                    V6mViolation::Undefined16(hw)
                };
                return Err((off, v));
            }
            off += 2;
        }
    }
    if off != bytes.len() {
        // An odd trailing byte: not a Thumb instruction stream at all.
        return Err((off, V6mViolation::Truncated(bytes[off] as u16)));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn le(hws: &[u16]) -> Vec<u8> {
        hws.iter().flat_map(|h| h.to_le_bytes()).collect()
    }

    /// The in-tree table equals the frozen LLVM-derived fixture, range for
    /// range — and is therefore checked over all 59,392 non-prefix halfwords.
    #[test]
    fn legal16_table_matches_llvm_fixture_1301() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../tests/fixtures/armv6m_legal16_1301.json"
        );
        let text = std::fs::read_to_string(path).expect("fixture");
        // The fixture is `{"legal_count": N, "legal_ranges": [[lo, hi], ...],
        // "provenance": "..."}` (no serde dependency here: read the integers
        // of the two numeric fields; provenance text is never parsed).
        let ints = |s: &str| -> Vec<u64> {
            s.split(|c: char| !c.is_ascii_digit())
                .filter(|s| !s.is_empty())
                .map(|s| s.parse().unwrap())
                .collect()
        };
        let field = |key: &str, end: &str| -> String {
            let start = text
                .find(key)
                .unwrap_or_else(|| panic!("fixture lacks {key}"))
                + key.len();
            let len = text[start..].find(end).expect("fixture field end");
            text[start..start + len].to_string()
        };
        let count = ints(&field("\"legal_count\":", ","));
        assert_eq!(count.len(), 1, "legal_count");
        let count = &count[0];
        let flat = ints(&field("\"legal_ranges\":", "]]"));
        assert!(
            !flat.is_empty() && flat.len() % 2 == 0,
            "legal_ranges shape"
        );
        let ranges: Vec<(u16, u16)> = flat.chunks(2).map(|c| (c[0] as u16, c[1] as u16)).collect();
        assert_eq!(ranges.as_slice(), LEGAL_16);
        let accepted = (0..=u16::MAX)
            .filter(|&h| !is_wide_prefix(h) && legal_16(h))
            .count() as u64;
        assert_eq!(accepted, *count);
        // No range strays into the 32-bit prefix space.
        assert!(
            LEGAL_16
                .iter()
                .all(|&(lo, hi)| (lo..=hi).all(|h| !is_wide_prefix(h)))
        );
    }

    /// The literal-pool reach obligation (#1301): synth's pool load is
    /// LDR.W (literal), 4 KB reach. ARMv6-M's LDR (literal) reaches 1020
    /// bytes forward. Encoded by the REAL encoder, the pool load must be
    /// refused, so no ARMv6-M function can carry a pool and the 4 KB island
    /// planner is never trusted for one. If this ever passes, a 16-bit pool
    /// load was introduced and its 1020-byte reach needs its own check.
    #[cfg(feature = "arm-cortex-m")]
    #[test]
    fn literal_pool_load_is_refused_1301() {
        use crate::arm_encoder::ArmEncoder;
        use synth_synthesis::rules::{ArmOp, Reg};
        let enc = ArmEncoder::new_thumb2_with_fpu(None);
        for rd in [Reg::R0, Reg::R3, Reg::R7, Reg::R12] {
            let bytes = enc
                .encode(&ArmOp::LdrSym {
                    rd,
                    symbol: "__synth_wasm_data".to_string(),
                    addend: 0,
                })
                .unwrap();
            let (at, v) = check_bytes(&bytes).unwrap_err();
            assert_eq!(at, 0);
            assert_eq!(v.class(), "wide load/store", "{rd:?}: {}", v.bytes_hex());
        }
    }

    /// Positive controls: one instance of each refused class, and the
    /// accepted forms synth emits for a trivial function.
    #[test]
    fn classes_1301() {
        // adds r2, r0, #1 ; mov r0, r2 ; push {r4, lr} ; pop {r4, pc} ; bne
        assert_eq!(
            check_bytes(&le(&[0x1C42, 0x4610, 0xB510, 0xBD10, 0xD10B])),
            Ok(())
        );
        // bl (any offset) and dmb sy pass
        assert_eq!(check_bytes(&le(&[0xF000, 0xF800, 0xF3BF, 0x8F5F])), Ok(()));
        let cls = |hws: &[u16]| check_bytes(&le(hws)).unwrap_err().1.class();
        assert_eq!(cls(&[0xBF08, 0x2001]), "IT block"); // it eq; movs
        assert_eq!(cls(&[0xB100]), "CBZ/CBNZ");
        assert_eq!(cls(&[0xF240, 0x002A]), "MOVW/MOVT"); // movw r0, #42
        assert_eq!(cls(&[0xF2C0, 0x0C10]), "MOVW/MOVT"); // movt r12, #0x10
        assert_eq!(cls(&[0xFBB0, 0xF0F0]), "UDIV/SDIV"); // udiv
        assert_eq!(cls(&[0xFB90, 0xF0F0]), "UDIV/SDIV"); // sdiv
        assert_eq!(cls(&[0xF8DF, 0x000C]), "wide load/store"); // ldr.w r0, [pc, #12]
        assert_eq!(
            cls(&[0xE92D, 0x41F0]),
            "wide load/store multiple (PUSH/POP/LDM/STM)"
        );
        assert_eq!(cls(&[0xF100, 0x0001]), "wide data-processing"); // add.w
        assert_eq!(
            cls(&[0xF000, 0xB800]),
            "wide branch or system (B.W/Bcc.W/MRS/MSR)"
        ); // b.w
        assert_eq!(cls(&[0xE9D0, 0x2300]), "LDRD/STRD/exclusive/table branch");
        // mrs r0, msp: ARMv6-M has it, synth never emits it — refused (stricter)
        assert_eq!(
            cls(&[0xF3EF, 0x8008]),
            "wide branch or system (B.W/Bcc.W/MRS/MSR)"
        );
        // 16-bit LDR (literal): in the ARMv6-M table, refused by its own rule.
        assert!(legal_16(0x4800) && legal_16(0x4FFF));
        assert_eq!(
            cls(&[0x4800]),
            "16-bit LDR literal: pool reach not checked on ARMv6-M"
        );
        assert_eq!(
            cls(&[0x4FFF]),
            "16-bit LDR literal: pool reach not checked on ARMv6-M"
        );
        assert_eq!(check_bytes(&le(&[0x4770])), Ok(())); // bx lr, just below the range
        assert_eq!(check_bytes(&le(&[0x5000])), Ok(())); // str r0, [r0, r0]
        // A violation's offset is the offset of the offending instruction.
        assert_eq!(
            check_bytes(&le(&[0x1C42, 0xF240, 0x002A])).unwrap_err().0,
            2
        );
        // Truncated: a 32-bit prefix with no second halfword.
        assert!(matches!(
            check_bytes(&le(&[0xF240])).unwrap_err().1,
            V6mViolation::Truncated(_)
        ));
    }
}
