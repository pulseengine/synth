fn compile(wasm: &[u8]) -> Result<Vec<String>, String> {
    let module = decode_wasm_module(wasm).expect("decodes");
    let cfg = CompileConfig {
        target: TargetSpec::cortex_a53(),
        relocatable: true,
        safety_bounds: SafetyBounds::Software,
        ..CompileConfig::default()
    };
    AArch64Backend::new()
        .compile_module(&module, &cfg)
        .map(|r| r.functions.into_iter().map(|f| f.name).collect())
        .map_err(|e| e.to_string())
}

/// RED on c20d37b2: every `(func (result i32))` was one structural class, so
/// `via_t1` compiled to an equality compare that also let `$u` through.
#[test]
fn strict_subtype_in_table_declines_1643() {
    let err = compile(HAND_SUB).expect_err("via_t1 must decline");
    assert!(
        err.contains("#1643"),
        "decline must name the subtype reason: {err}"
    );
}

#[test]
fn exact_equality_dispatches_still_compile_1643() {
    let names = compile(HAND_SUB_NO_T1).expect("via_t2/via_u compile");
    assert!(names.iter().any(|n| n == "via_t2") && names.iter().any(|n| n == "via_u"));
}
