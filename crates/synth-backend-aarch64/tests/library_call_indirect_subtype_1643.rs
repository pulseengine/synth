//! #1643: `call_indirect` under WASM 3.0 declared subtyping, through the
//! published `Backend::compile_module` API on AArch64.
//!
//! Every AArch64 dispatch type-checks by ONE equality compare of class ids.
//! §4.4.8 checks `<:`, so for an expected type with a strict declared
//! subtype in the table, equality would trap a call the spec makes: the
//! lowering must decline loudly. `synth compile -b aarch64` reaches the same
//! decision through `PlanInputs` (gated by
//! scripts/repro/call_indirect_type_1643_differential.py); this pins the
//! `compile_module` route, which the CLI does not take.

